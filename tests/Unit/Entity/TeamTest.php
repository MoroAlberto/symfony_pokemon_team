<?php

namespace App\Tests\Unit\Entity;

use App\Entity\Pokemon;
use App\Entity\Team;
use App\Entity\Type;
use PHPUnit\Framework\TestCase;

class TeamTest extends TestCase
{
    public function testAddPokemonSetsTheTeamOnThePokemon(): void
    {
        $team = new Team();
        $pokemon = new Pokemon();

        $team->addPokemon($pokemon);

        $this->assertSame($team, $pokemon->getTeam());
        $this->assertCount(1, $team->getPokemon());
    }

    public function testAddingTheSamePokemonTwiceKeepsOneCopy(): void
    {
        $team = new Team();
        $pokemon = new Pokemon();

        $team->addPokemon($pokemon);
        $team->addPokemon($pokemon);

        $this->assertCount(1, $team->getPokemon());
    }

    public function testRemovePokemonUnsetsTheTeamOnThePokemon(): void
    {
        $team = new Team();
        $pokemon = new Pokemon();
        $team->addPokemon($pokemon);

        $team->removePokemon($pokemon);

        $this->assertNull($pokemon->getTeam());
        $this->assertCount(0, $team->getPokemon());
    }

    public function testRemovePokemonDoesNotTouchAPokemonOfAnotherTeam(): void
    {
        $team = new Team();
        $otherTeam = new Team();
        $pokemon = new Pokemon();
        $otherTeam->addPokemon($pokemon);

        $team->removePokemon($pokemon);

        $this->assertSame($otherTeam, $pokemon->getTeam());
    }

    public function testGetAllPokemonTypeOfAnEmptyTeam(): void
    {
        $this->assertSame([], (new Team())->getAllPokemonType());
    }

    public function testGetAllPokemonTypeIsUniqueAndSortedByNameAndIndexedById(): void
    {
        $water = $this->createType(1, 'water');
        $fire = $this->createType(2, 'fire');
        $flying = $this->createType(3, 'flying');

        $team = new Team();
        $team->addPokemon((new Pokemon())->addType($water));
        $team->addPokemon((new Pokemon())->addType($fire)->addType($flying));
        $team->addPokemon((new Pokemon())->addType($fire));

        $this->assertSame([2 => 'fire', 3 => 'flying', 1 => 'water'], $team->getAllPokemonType());
    }

    private function createType(int $id, string $name): Type
    {
        $type = (new Type())->setName($name);
        // The id is normally generated by the database
        (new \ReflectionProperty(Type::class, 'id'))->setValue($type, $id);

        return $type;
    }
}
